#include "Arithmatic Perform.h"
#include <iostream>

using namespace std;

double Addition(double a,double b)
{
    double sum;
    sum = a+b;
    return sum;
}

double Subtraction(double a,double b)
{
    double sub;
    sub = a-b;
    return sub;
}

double Multiplication(double a,double b)
{
    double mul;
    mul = a*b;
    return mul;
}

double Division(double a,double b)
{
    double div;
    div = a/b;
    return div;
}
